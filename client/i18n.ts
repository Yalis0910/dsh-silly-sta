let current = 'zh' as 'zh' | 'en'
const listeners = new Set<() => void>()

/** Switch the plugin's display language. Returns whether it changed. */
export function setLocale(lang: string): boolean {
  const next = /^en/i.test(lang) ? 'en' : 'zh'
  if (next === current) return false
  current = next
  for (const listener of listeners) listener()
  return true
}

export function getLocale(): 'zh' | 'en' {
  return current
}

/** Non-reactive translation (for non-component contexts). */
export function t(key: string): string {
  return (current === 'en' ? en[key as sillyStaKey] : zh[key as sillyStaKey]) ?? key
}

/** Reactive translation hook: components re-render on locale change. */
export function useT(): (key: string) => string {
  const [, force] = useState(0)
  useEffect(() => {
    const listener = () => force(value => value + 1)
    listeners.add(listener)
    return () => {
      listeners.delete(listener)
    }
  }, [])
  return t
}

/** Replace {name}-style placeholders in a translated string. */
export function tf(key: string, params: Record<string, string | number>): string {
  let text = t(key)
  for (const [name, value] of Object.entries(params)) text = text.replaceAll('{' + name + '}', String(value))
  return text
}

